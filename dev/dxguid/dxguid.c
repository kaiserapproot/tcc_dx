/*
 * dxguid.c - DirectX / COM GUID definitions for dev\lib\libdxguid.a (TCC).
 *
 * Why this file exists
 *   dev\lib\libdxguid.a used to be the mingw-w64 lib64 archive: one COFF
 *   x86-64 object (lib64_libdxguid_a-dxguid.o).  TCC links ELF objects only,
 *   so `-ldxguid` failed with "invalid object file".  This source rebuilds
 *   the same library in a form TCC can link.
 *
 * Where the values come from
 *   The 1090 names and their 16 bytes were read out of that COFF archive
 *   (sha256 13DE09BE7E4D740EEAE184B068A1F36833F293F1006F6E6D2FBCB1F937BD7334)
 *   with llvm-readobj and written here, one DXGUID() line per symbol, sorted
 *   by name.  Every value was checked against the archive (1090 of 1090);
 *   verify_original.bat repeats that check from git history.
 *
 * Why the definitions are weak
 *   mingw declares these with DECLSPEC_SELECTANY (COMDAT: duplicates are
 *   merged).  TCC has no COMDAT, so a plain definition here would collide
 *   ("defined twice") with a translation unit that defines the same GUID
 *   itself through <initguid.h>.  A weak definition lets the program's own
 *   definition win, which keeps the library usable next to INITGUID code.
 *
 * Target: x86-64 only (ELF64 relocatable).  Rebuild with make_lib.bat.
 */
